require "spec_helper"

RSpec.describe "Sequel::Extensions::BrutMigrations" do
  def mock_db
    Sequel.mock(host: :postgres)
  end

  it "can be loaded into more than one database without recursive add_column/add_foreign_key aliases" do
    first_db = mock_db
    second_db = mock_db
    first_db.extension :brut_migrations
    second_db.extension :brut_migrations

    first_db.alter_table(:widgets) do
      add_column :name, :text
      add_foreign_key :gadget_id, :gadgets
    end

    sql = first_db.sqls.join("\n")
    expect(sql).to include(%{ADD COLUMN "name" text NOT NULL})
    expect(sql).to include(%{ADD COLUMN "gadget_id" integer NOT NULL REFERENCES "gadgets"})
  end

  it "requires a comment when create_table has no options hash" do
    db = mock_db
    db.extension :brut_migrations

    expect {
      db.create_table(:widgets) do
        column :name, :text
      end
    }.to raise_error(ArgumentError, /must have a comment/)
  end

  it "requires a comment when create_table has an options hash without one" do
    db = mock_db
    db.extension :brut_migrations

    expect {
      db.create_table(:widgets, {}) do
        column :name, :text
      end
    }.to raise_error(ArgumentError, /must have a comment/)
  end

  it "accepts a table with a comment" do
    db = mock_db
    db.extension :brut_migrations

    db.create_table(:widgets, comment: "Widgets") do
      column :name, :text
    end

    expect(db.sqls.join).to include("comment on table widgets is 'Widgets'")
  end

  it "uses CreateTableGenerator#key to create unique indexes" do
    db = mock_db
    db.extension :brut_migrations

    db.create_table(:widgets, comment: "Widgets") do
      key [:name]
      column :name, :text
    end

    expect(db.sqls.join).to include(%{CREATE UNIQUE INDEX "widgets_name_index"})
  end

  it "applies the create_table defaults while respecting explicit nullability" do
    db = mock_db
    db.extension :brut_migrations

    db.create_table(:widgets, comment: "Widgets") do
      column :name, :text
      column :deactivated_at, :timestamptz, null: true
    end

    sql = db.sqls.join("\n")
    expect(sql).to include(%{"id" integer GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY})
    expect(sql).to include(%{"name" text NOT NULL})
    expect(sql).to include(%{"deactivated_at" timestamptz NULL})
    expect(sql).to include(%{"created_at" timestamptz NOT NULL})
  end

  it "adds an external id column when requested" do
    db = mock_db
    db.extension :brut_migrations

    db.create_table(:widgets, comment: "Widgets", external_id: true) do
      column :name, :text
    end

    expect(db.sqls.join).to include(%{ADD COLUMN "external_id" citext NOT NULL UNIQUE})
  end

  it "does not require comments or apply defaults to Sequel's migration tables" do
    db = mock_db
    db.extension :brut_migrations

    db.create_table("schema_migrations") do
      column :filename, :text
    end
    db.create_table("schema_info") do
      column :version, :integer
    end

    sql = db.sqls.join("\n")
    expect(sql).to include(%{CREATE TABLE "schema_migrations"})
    expect(sql).to include(%{CREATE TABLE "schema_info"})
    expect(sql).not_to include("created_at")
    expect(sql).not_to include("comment on table")
  end

  it "applies alter_table column defaults while respecting explicit nullability" do
    db = mock_db
    db.extension :brut_migrations

    db.alter_table(:widgets) do
      add_column :name, :text
      add_column :deactivated_at, :timestamptz, null: true
    end

    sql = db.sqls.join("\n")
    expect(sql).to include(%{ADD COLUMN "name" text NOT NULL})
    expect(sql).to include(%{ADD COLUMN "deactivated_at" timestamptz NULL})
  end

  it "creates an index for add_foreign_key by default" do
    db = mock_db
    db.extension :brut_migrations

    db.alter_table(:widgets) do
      add_foreign_key :gadget_id, :gadgets
    end

    sql = db.sqls.join("\n")
    expect(sql).to include(%{ADD COLUMN "gadget_id" integer NOT NULL REFERENCES "gadgets"})
    expect(sql).to include(%{CREATE INDEX "widgets_gadget_id_index" ON "widgets" ("gadget_id")})
  end

  it "applies database-level add_column defaults while respecting explicit nullability" do
    db = mock_db
    db.extension :brut_migrations

    db.add_column :widgets, :name, :text
    db.add_column :widgets, :deactivated_at, :timestamptz, null: true

    sql = db.sqls.join("\n")
    expect(sql).to include(%{ADD COLUMN "name" text NOT NULL})
    expect(sql).to include(%{ADD COLUMN "deactivated_at" timestamptz NULL})
  end
end
